"use strict";
var a = 1;
while (a <= 10) {
    console.log(a);
    a++;
}
// To print even number
console.log("print Even number");
var i = 2;
while (i <= 10) {
    console.log(i);
    i += 2;
}
// print odd number
var j = 1;
while (j <= 10) {
    if (j % 2 != 0) {
        console.log(j);
    }
    j += 1;
}
// reverse number
i = 10;
while (i > 0) {
    console.log(i);
    i--;
}
